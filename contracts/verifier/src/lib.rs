//   IC[0]: constant term
//   IC[1]: merkle_root
//   IC[2]: employer_id
//   IC[3]: nullifier       (circuit output)
//   IC[4]: claimed_amount  (circuit output)
//
// Full pairing verification (e(A, B) == e(alpha, beta) * e(vk_x, gamma) * e(C, delta))
// requires BLS12-381 host functions that are pending inclusion in Soroban's
