use soroban_sdk::token;

#[contract]
pub struct AegisPayVerifier;

// ── Error Codes ──────────────────────────────────────────────────────────────
#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq, PartialOrd, Ord)]
#[repr(u32)]
pub enum Error {
    AlreadyInitialized  = 1,
    NotInitialized      = 2,
    Unauthorized        = 3,
    InvalidProof        = 4,
    NullifierSpent      = 5,
    InsufficientFunds   = 6,
    RootNotActive       = 7,  // root not in active batch registry
    InvalidEmployer     = 8,
    RootAlreadyActive   = 9,  // batch root already added
    RootNotFound        = 10, // tried to disable root that doesn't exist
}

// ── Data Types ───────────────────────────────────────────────────────────────
/// Groth16 BLS12-381 proof elements.
/// - `a`: G1 compressed point (48 bytes on BLS12-381)
/// - `b`: G2 compressed point (96 bytes on BLS12-381)
/// - `c`: G1 compressed point (48 bytes on BLS12-381)
///
/// The sizes are padded to match the BytesN constraints while remaining
/// compatible with the snarkjs serialisation used in the frontend.
#[contracttype]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Proof {
    pub a: BytesN<64>,   // G1 point (pi_a, padded to 64 bytes)
    pub b: BytesN<128>,  // G2 point (pi_b, padded to 128 bytes)
    pub c: BytesN<64>,   // G1 point (pi_c, padded to 64 bytes)
}

/// The four public signals exposed by the PayrollClaim(10) Circom circuit:
///   public [merkleRoot, employerId] → outputs: nullifier, claimedAmount
#[contracttype]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PublicInputs {
    pub merkle_root:    BytesN<32>,
    pub employer_id:    BytesN<32>,
    pub nullifier:      BytesN<32>,
    pub claimed_amount: i128,
}

// ── Storage Keys ─────────────────────────────────────────────────────────────
#[contracttype]
#[derive(Clone)]
pub enum DataKey {
    Employer,
    EmployerId,
    UsdcToken,
    PayrollRoot(BytesN<32>), // per-batch root registry
    NullifierSpent(BytesN<32>),
}

